package practic;

public class arithmeticoperator {
    public static void main(String[] args){
        //整数参与计算,结果只能得到整数
        //小数参与运算,结果有可能是不精确的小数
        System.out.println(3 + 2);
        System.out.println(3 - 2);
        System.out.println(3 * 2);
        System.out.println(5 / 2);
        System.out.println(5.0 / 2);
        System.out.println(3 % 2);
        System.out.println(10 % 5);
        System.out.println(3.1 - 2.2);



    }
}
